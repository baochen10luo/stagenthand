// NormalizeToTraditional converts simplified Chinese characters in s to Traditional.
func NormalizeToTraditional(s string) string {
	runes := []rune(s)
	for i, r := range runes {
		if t, ok := simplifiedToTraditional[r]; ok {
			runes[i] = t
		}
	}
	return string(runes)
}
